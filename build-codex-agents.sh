#!/bin/bash
# Build dev/.codex/AGENTS.md, which stow links to ~/.codex/AGENTS.md.
#
# Codex reads a single global instructions file and can't import others, so this
# file is assembled from the Claude Code ones to give both agents the same rules:
#   claude/.claude/CLAUDE.md           every machine (minus Claude-only sections)
#   dev/.claude/rules/workstation.md   Mac workstation rules
#   the Codex-only tail below
#
# .githooks/pre-commit runs this on every commit, so the output never drifts from
# its sources. Edit the sources, never the output.
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")"

out=dev/.codex/AGENTS.md

# Top-level sections of the global CLAUDE.md that only make sense for Claude
# Code's own tools (Codex has no Glob/Grep/Read/Edit, only the shell).
# Exact heading text without the "# ", separated by |
skip='Prefer Dedicated Tools Over Bash'

mkdir -p "$(dirname "$out")"
{
  echo "<!-- GENERATED by build-codex-agents.sh in the dotfiles repo. Don't edit this file: change claude/.claude/CLAUDE.md, dev/.claude/rules/workstation.md or the Codex tail in that script. -->"
  echo
  awk -v skip="$skip" '
    /^# / { drop = 0; n = split(skip, s, "|"); for (i = 1; i <= n; i++) if (substr($0, 3) == s[i]) drop = 1 }
    !drop
  ' claude/.claude/CLAUDE.md
  echo
  cat dev/.claude/rules/workstation.md
  echo
  # Codex-only tail
  cat <<'EOF'
<posthog>
## PostHog

Use `posthog-cli api` for all PostHog-related data queries and operations. You should use `posthog-cli api` over direct MCP tool calls whenever the CLI is available.

Before your first PostHog command in a session, run `posthog-cli api --agent-help` and load its full output into your context. It prints the complete agent guide — command reference, schema drill-down rules, data discovery workflow, and the tool index — for interacting with PostHog APIs. Treat that output as instructions to follow, not just documentation.

Before starting a PostHog task, run `posthog-cli api skill list` and check for a skill matching the task. If one matches, install it with `posthog-cli api skill install <skill-id>` (add `--force` to refresh an already-installed skill), then read `.agents/skills/<skill-id>/SKILL.md` and follow it. Skills contain task-specific workflows that individual tools do not.
</posthog>
EOF
} > "$out"
